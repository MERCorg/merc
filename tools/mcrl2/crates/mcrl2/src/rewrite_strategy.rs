use mcrl2_sys::cxx::UniquePtr;
use mcrl2_sys::data::ffi;
use merc_utilities::MercError;
use merc_utilities::PhantomUnsend;

use crate::DataSpecification;

/// The rewrite strategy of a [DataRewriter].
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
#[cfg_attr(feature = "clap", derive(clap::ValueEnum))]
pub enum RewriteStrategy {
    /// The just-in-time rewriter of mCRL2
    #[default]
    Jitty,
    /// The compiling just-in-time rewriter of mCRL2 (requires 'jittyc' feature)
    Jittyc,
    /// The just-in-time rewriter of mCRL2 with a prover for conditions
    Jittyp,
    /// The compiling just-in-time rewriter of mCRL2 with a prover for conditions (requires 'jittyc' feature)
    Jittycp,
}

impl RewriteStrategy {
    /// Returns the mCRL2 strategy, or `None` when it is not compiled in.
    fn to_ffi(self) -> Option<ffi::RewriteStrategy> {
        match self {
            RewriteStrategy::Jitty => Some(ffi::RewriteStrategy::Jitty),
            RewriteStrategy::Jittyp => Some(ffi::RewriteStrategy::JittyProver),
            #[cfg(feature = "jittyc")]
            RewriteStrategy::Jittyc => Some(ffi::RewriteStrategy::JittyCompiling),
            #[cfg(feature = "jittyc")]
            RewriteStrategy::Jittycp => Some(ffi::RewriteStrategy::JittyCompilingProver),
            #[cfg(not(feature = "jittyc"))]
            RewriteStrategy::Jittyc | RewriteStrategy::Jittycp => None,
        }
    }

    /// Returns true iff this strategy uses the compiling rewriter.
    fn is_compiling(self) -> bool {
        matches!(self, RewriteStrategy::Jittyc | RewriteStrategy::Jittycp)
    }
}

/// Tells mCRL2 which script compiles the code generated by the compiling
/// rewriter: the script installed with the executable by `xtask package`, or
/// otherwise the script generated when building mcrl2-sys.
///
/// mCRL2 only reads the script from the `MCRL2_COMPILEREWRITER` environment
/// variable, which a value chosen by the user takes precedence over. Setting it
/// is not thread safe, so this happens once, when the first compiling rewriter
/// is created.
#[cfg(all(feature = "jittyc", unix))]
fn set_compile_rewriter_script() {
    static ONCE: std::sync::Once = std::sync::Once::new();
    ONCE.call_once(|| match installed_compile_rewriter_script() {
        Some(script) => ffi::mcrl2_data_set_compile_rewriter_script(&script.to_string_lossy()),
        None => ffi::mcrl2_data_set_compile_rewriter_script(mcrl2_sys::COMPILE_REWRITER_SCRIPT),
    });
}

/// The mCRL2 data rewriter for one data specification, which the rewriting
/// contexts ([crate::LearnSuccessorsContext], [crate::PbesRewriteContext]) clone.
///
/// Creating a rewriter can be expensive: the compiling rewriter generates and
/// compiles code for the rewrite rules. A clone shares that code, so create
/// one rewriter per data specification and pass it to every context.
pub struct DataRewriter {
    rewriter: UniquePtr<ffi::rewriter>,

    /// The rewriter holds thread-affine `aterm`s, so it must be destroyed on
    /// the thread that created it.
    _marker: PhantomUnsend,
}

// SAFETY: the only access through a shared reference is cloning the rewriter
// (see [DataRewriter::get]), which mCRL2 supports from several threads at once:
// its parallel explorer clones one global rewriter in every worker thread.
unsafe impl Sync for DataRewriter {}

impl DataRewriter {
    /// Creates a rewriter for `data_spec` that uses `strategy`.
    ///
    /// Returns an error when `strategy` is not compiled in, or when the rewriter
    /// cannot be created, for example when the compiling rewriter fails to
    /// compile its generated code.
    ///
    /// The first compiling rewriter sets the `MCRL2_COMPILEREWRITER` environment
    /// variable, unless the user set it, which is not thread safe. Create it
    /// before starting other threads.
    pub fn new(data_spec: &DataSpecification, strategy: RewriteStrategy) -> Result<Self, MercError> {
        let mcrl2_strategy = strategy
            .to_ffi()
            .filter(|_| !strategy.is_compiling() || cfg!(unix))
            .ok_or_else(|| {
                format!(
                    "The {strategy:?} rewriter requires the 'jittyc' feature, which is only supported on unix platforms"
                )
            })?;

        #[cfg(all(feature = "jittyc", unix))]
        if strategy.is_compiling() {
            set_compile_rewriter_script();
        }

        let data_spec = data_spec
            .get()
            .as_ref()
            .expect("The data specification is always defined");
        Ok(DataRewriter {
            rewriter: ffi::mcrl2_data_create_rewriter(data_spec, mcrl2_strategy)?,
            _marker: PhantomUnsend::default(),
        })
    }

    /// Returns the underlying rewriter, which may only be passed to the
    /// context constructors that clone it.
    pub(crate) fn get(&self) -> &ffi::rewriter {
        self.rewriter.as_ref().expect("The rewriter is always defined")
    }
}

/// Returns the `jittyc/mcrl2compilerewriter` script next to the executable,
/// where `xtask package` installs it, if it exists.
#[cfg(all(feature = "jittyc", unix))]
fn installed_compile_rewriter_script() -> Option<std::path::PathBuf> {
    let exe = std::env::current_exe().ok()?;
    let script = exe.parent()?.join("jittyc").join("mcrl2compilerewriter");
    script.is_file().then_some(script)
}
