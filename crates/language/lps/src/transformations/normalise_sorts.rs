/// Rewrites every sort of `lps` to the canonical form that merc's type checker and lowering use.
///
/// Both toolsets give every sort a unique representative, but they pick different ones for an alias
/// of a compound sort. mCRL2 normalises `sort C = List(Nat)` *towards the name*, so a `.lps` file
/// mentions `C` even where the specification wrote `List(Nat)`, whereas merc expands the alias to
/// `List(Nat)`. The system defined equations are generated by merc, so without this pass their
/// symbols would not be the ones occurring in the file and no rule would ever match. Hence, every
/// alias is expanded, except that an alias of a structured sort keeps its name, as it does in both
/// toolsets, because structured sorts are nominal and may be recursive.
pub fn normalise_sorts(lps: &LinearProcessSpecification) -> LinearProcessSpecification {
    let expansions = alias_expansions(lps.data_specification.aliases());
    if expansions.is_empty() {
        return lps.clone();
    }

    let normaliser = SortNormaliser { expansions };
    let label = |label: &ActionLabel| ActionLabel {
        name: label.name.clone(),
        sorts: label.sorts.iter().map(|sort| normaliser.apply(sort)).collect(),
    };

    let data = &lps.data_specification;
    LinearProcessSpecification {
        data_specification: Mcrl2DataSpecification::new(
            data.sorts().to_vec(),
            data.aliases()
                .iter()
                .map(|alias| SortAlias::new(alias.name().protect(), normaliser.apply(&alias.reference().protect())))
                .collect(),
            data.constructors()
                .iter()
                .map(|symbol| normaliser.apply(symbol))
                .collect(),
            data.mappings().iter().map(|symbol| normaliser.apply(symbol)).collect(),
            data.equations()
                .iter()
                .map(|equation| normaliser.apply(equation))
                .collect(),
        ),
        action_labels: lps.action_labels.iter().map(label).collect(),
        global_variables: lps
            .global_variables
            .iter()
            .map(|variable| normaliser.apply(variable))
            .collect(),
        process_parameters: lps
            .process_parameters
            .iter()
            .map(|variable| normaliser.apply(variable))
            .collect(),
        action_summands: lps
            .action_summands
            .iter()
            .map(|summand| ActionSummand {
                summation_variables: summand
                    .summation_variables
                    .iter()
                    .map(|variable| normaliser.apply(variable))
                    .collect(),
                condition: normaliser.apply(&summand.condition),
                action: MultiAction {
                    actions: summand
                        .action
                        .actions
                        .iter()
                        .map(|action| Action {
                            label: label(&action.label),
                            arguments: action
                                .arguments
                                .iter()
                                .map(|argument| normaliser.apply(argument))
                                .collect(),
                        })
                        .collect(),
                    time: summand.action.time.as_ref().map(|time| normaliser.apply(time)),
                },
                next_state: summand
                    .next_state
                    .iter()
                    .map(|value| value.as_ref().map(|value| normaliser.apply(value)))
                    .collect(),
            })
            .collect(),
        deadlock_summands: lps
            .deadlock_summands
            .iter()
            .map(|summand| DeadlockSummand {
                summation_variables: summand
                    .summation_variables
                    .iter()
                    .map(|variable| normaliser.apply(variable))
                    .collect(),
                condition: normaliser.apply(&summand.condition),
                time: summand.time.as_ref().map(|time| normaliser.apply(time)),
            })
            .collect(),
        initial_state: lps.initial_state.iter().map(|value| normaliser.apply(value)).collect(),
    }
}

/// Maps the name of every alias that has to be expanded to its fully expanded definition.
fn alias_expansions(aliases: &[SortAlias]) -> HashMap<ATerm, ATerm> {
    let definitions: HashMap<ATerm, ATerm> = aliases
        .iter()
        .filter(|alias| !is_structured_sort(&alias.reference()))
        .map(|alias| (alias.name().protect().into(), alias.reference().protect().into()))
        .collect();

    definitions
        .keys()
        .map(|name| (name.clone(), expand(name, &definitions, &mut Vec::new())))
        .collect()
}

/// Expands the aliases in `sort`. An alias that is reached again while it is being expanded is kept
/// as a name, so that recursion through an inline `struct` terminates.
fn expand(sort: &ATerm, definitions: &HashMap<ATerm, ATerm>, visited: &mut Vec<ATerm>) -> ATerm {
    if let Some(definition) = definitions.get(sort) {
        if visited.contains(sort) {
            return sort.clone();
        }
        visited.push(sort.clone());
        let result = expand(definition, definitions, visited);
        visited.pop();
        return result;
    }

    if sort.get_head_symbol().arity() == 0 || is_basic_sort(sort) {
        return sort.clone();
    }

    let arguments: Vec<ATerm> = sort
        .arguments()
        .map(|argument| expand(&argument.protect(), definitions, visited))
        .collect();
    ATerm::with_args(&sort.get_head_symbol().protect(), &arguments).protect()
}

struct SortNormaliser {
    expansions: HashMap<ATerm, ATerm>,
}

impl SortNormaliser {
    fn apply<T: Clone + From<ATerm> + Into<ATerm>>(&self, term: &T) -> T {
        let expansions = &self.expansions;
        T::from(THREAD_TERM_POOL.with(|tp| {
            apply(tp, &term.clone().into(), &|_, subterm| {
                if is_basic_sort(subterm) {
                    Some(expansions.get(subterm).cloned().unwrap_or_else(|| subterm.clone()))
                } else {
                    None
                }
            })
        }))
    }
}

#[cfg(test)]
mod tests {
    use merc_data::BasicSort;
    use merc_data::ContainerSortKind;
    use merc_data::DataVariable;
    use merc_data::Mcrl2DataSpecification;
    use merc_data::SortAlias;
    use merc_data::SortCons;
    use merc_data::SortExpression;

    use super::normalise_sorts;
    use crate::LinearProcessSpecification;

    fn lps_with_parameter(alias: SortAlias, parameter: SortExpression) -> LinearProcessSpecification {
        LinearProcessSpecification {
            data_specification: Mcrl2DataSpecification::new(
                Vec::new(),
                vec![alias],
                Vec::new(),
                Vec::new(),
                Vec::new(),
            ),
            action_labels: Vec::new(),
            global_variables: Vec::new(),
            process_parameters: vec![DataVariable::with_sort("x", parameter.copy())],
            action_summands: Vec::new(),
            deadlock_summands: Vec::new(),
            initial_state: Vec::new(),
        }
    }

    #[test]
    #[cfg_attr(miri, ignore)]
    fn test_alias_of_container_is_expanded() {
        let list: SortExpression = SortCons::new(ContainerSortKind::List, BasicSort::new("Nat").into()).into();
        let alias = BasicSort::new("C");
        let lps = lps_with_parameter(SortAlias::new(alias.clone(), list.clone()), alias.into());

        let normalised = normalise_sorts(&lps);
        assert_eq!(normalised.process_parameters[0].sort().protect(), list);
    }

    #[test]
    #[cfg_attr(miri, ignore)]
    fn test_alias_chain_is_expanded() {
        let alias = BasicSort::new("A");
        let target = BasicSort::new("Nat");
        let lps = lps_with_parameter(SortAlias::new(alias.clone(), target.clone().into()), alias.into());

        let normalised = normalise_sorts(&lps);
        assert_eq!(
            normalised.process_parameters[0].sort().protect(),
            SortExpression::from(target)
        );
    }
}
